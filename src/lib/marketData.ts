export function formatCompactUsd(val: number): string {
  if (val >= 1_000_000_000) return `$${(val / 1_000_000_000).toFixed(2)}B`;
  if (val >= 1_000_000) return `$${(val / 1_000_000).toFixed(2)}M`;
  if (val >= 1_000) return `$${(val / 1_000).toFixed(1)}K`;
  return `$${val.toFixed(2)}`;
}

export function formatTokenPrice(price: number): string {
  if (price >= 1000) return `$${price.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  if (price >= 1) return `$${price.toFixed(2)}`;
  if (price >= 0.01) return `$${price.toFixed(4)}`;
  if (price >= 0.0001) return `$${price.toFixed(6)}`;
  // Axiom subscript notation for micro-prices e.g. $0.0₄182
  const str = price.toFixed(10);
  const match = str.match(/^0\.(0+)([1-9]\d{0,2})/);
  if (match) {
    const zeros = match[1].length;
    const subscripts = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇', '₈', '₉'];
    const sub = String(zeros)
      .split('')
      .map((d) => subscripts[Number(d)] || d)
      .join('');
    return `$0.0${sub}${match[2]}`;
  }
  return `$${price.toFixed(6)}`;
}
